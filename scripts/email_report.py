"""
Bonus Challenge B5 – Automated HTML Email Report Generator
==========================================================
Generates a beautiful weekly performance summary HTML email.
It builds a scorecard of the top 5 funds by Sharpe Ratio,
saves it locally as 'reports/weekly_report.html' for preview,
and provides the logic to actually send it via Gmail SMTP.

Run from project root:
    python scripts/email_report.py
"""

import pandas as pd
import smtplib
from email.message import EmailMessage
from datetime import datetime
from pathlib import Path

# ── Paths ──────────────────────────────────────────────────────────────────
ROOT      = Path(__file__).parent.parent
PERF_PATH = ROOT / "data" / "processed" / "07_scheme_performance.csv"
OUT_HTML  = ROOT / "reports" / "weekly_report.html"

# ── Email Settings (Update these to actually send) ─────────────────────────
SENDER_EMAIL = "your_email@gmail.com"
APP_PASSWORD = "your_16_digit_app_password" # Use Gmail App Password, not real password
RECIPIENT_EMAIL = "recipient@email.com"

# ── Load Data ──────────────────────────────────────────────────────────────
def generate_html_report():
    perf_df = pd.read_csv(PERF_PATH)
    
    # Get top 5 funds by Sharpe Ratio for the weekly highlight
    top5 = perf_df.nlargest(5, "sharpe_ratio")[
        ["scheme_name", "category", "return_3yr_pct", "sharpe_ratio", "risk_grade"]
    ]
    
    # Build HTML Table Rows
    table_rows = ""
    for _, row in top5.iterrows():
        table_rows += f"""
        <tr>
            <td style="padding: 12px; border-bottom: 1px solid #ddd;">{row['scheme_name']}</td>
            <td style="padding: 12px; border-bottom: 1px solid #ddd;">{row['category']}</td>
            <td style="padding: 12px; border-bottom: 1px solid #ddd; color: #2e7d32; font-weight: bold;">{row['return_3yr_pct']}%</td>
            <td style="padding: 12px; border-bottom: 1px solid #ddd;">{row['sharpe_ratio']}</td>
            <td style="padding: 12px; border-bottom: 1px solid #ddd;">{row['risk_grade']}</td>
        </tr>
        """
        
    date_str = datetime.now().strftime("%B %d, %Y")
    
    # Build the full HTML email
    html_content = f"""
    <!DOCTYPE html>
    <html>
    <head>
        <meta charset="utf-8">
        <style>
            body {{ font-family: 'Segoe UI', Arial, sans-serif; background-color: #f4f6f8; margin: 0; padding: 20px; }}
            .container {{ max-width: 700px; margin: 0 auto; background-color: #ffffff; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 6px rgba(0,0,0,0.1); }}
            .header {{ background-color: #0d2d52; color: #ffffff; padding: 20px; text-align: center; }}
            .header h1 {{ margin: 0; font-size: 24px; }}
            .content {{ padding: 30px; color: #333333; line-height: 1.6; }}
            .footer {{ background-color: #f1f1f1; color: #777777; padding: 15px; text-align: center; font-size: 12px; }}
            table {{ width: 100%; border-collapse: collapse; margin-top: 20px; }}
            th {{ background-color: #00a8e8; color: #ffffff; text-align: left; padding: 12px; }}
        </style>
    </head>
    <body>
        <div class="container">
            <div class="header">
                <h1>📈 Bluestock MF Weekly Analytics Report</h1>
                <p style="margin-top: 5px; color: #93b8d4;">{date_str}</p>
            </div>
            
            <div class="content">
                <h2>Hello Investor,</h2>
                <p>Here is your automated weekly summary of the top-performing mutual funds across our tracked database. This week's highlights are sorted by the highest risk-adjusted returns (Sharpe Ratio).</p>
                
                <table>
                    <thead>
                        <tr>
                            <th>Fund Name</th>
                            <th>Category</th>
                            <th>3Y Return</th>
                            <th>Sharpe</th>
                            <th>Risk Grade</th>
                        </tr>
                    </thead>
                    <tbody>
                        {table_rows}
                    </tbody>
                </table>
                
                <p style="margin-top: 30px;">
                    Log into your <a href="#" style="color: #00a8e8; text-decoration: none; font-weight: bold;">Bluestock Power BI Dashboard</a> to view full interactive insights and live NAV data.
                </p>
            </div>
            
            <div class="footer">
                Automated Report generated by Bluestock ETL Pipeline.<br>
                Please do not reply to this email.
            </div>
        </div>
    </body>
    </html>
    """
    return html_content

def save_local_preview(html_content):
    with open(OUT_HTML, "w", encoding="utf-8") as f:
        f.write(html_content)
    print(f"[OK] Saved HTML preview to {OUT_HTML}")

def send_email(html_content):
    if SENDER_EMAIL == "your_email@gmail.com":
        print("[WARNING] Skipping actual email send. Update credentials in the script to send real emails.")
        return
        
    msg = EmailMessage()
    msg['Subject'] = f"📈 Bluestock Weekly MF Report - {datetime.now().strftime('%b %d')}"
    msg['From'] = SENDER_EMAIL
    msg['To'] = RECIPIENT_EMAIL
    
    # Set the content to be HTML
    msg.set_content("Please enable HTML to view this message.")
    msg.add_alternative(html_content, subtype='html')
    
    try:
        # Connect to Gmail SMTP server
        print("Connecting to SMTP server...")
        with smtplib.SMTP_SSL('smtp.gmail.com', 465) as smtp:
            smtp.login(SENDER_EMAIL, APP_PASSWORD)
            smtp.send_message(msg)
            print("✅ Email sent successfully!")
    except Exception as e:
        print(f"❌ Failed to send email: {e}")

if __name__ == "__main__":
    html_out = generate_html_report()
    save_local_preview(html_out)
    send_email(html_out)
